/**
 * Принимать ли новое значение `limitPrice` из стора в поле тикета.
 *
 * @remarks Мост из книги в тикет висит на `useTradeStore.subscribe`, а
 * zustand v5 в `set()` всегда собирает новый объект — листенер зовётся на
 * КАЖДУЮ запись в стор, чем бы она ни была. Селекторной формы у стора нет: он
 * создан без `subscribeWithSelector`. Значит отсекать лишние срабатывания
 * приходится здесь.
 *
 * Два отказа, и они разные:
 * - цена не менялась — писала не книга, а кто-то ещё (в Ф2 на этот же стор
 *   садится весь тикет, и первый же `setSide` иначе насильно вернул бы
 *   вкладку Limit и затёр цену, введённую руками);
 * - цена сменилась в «нет значения» — это `setOrderType`, который пишет
 *   `limitPrice: type === MARKET ? null : undefined`. Такую запись принимать
 *   нельзя, иначе поле обнулялось бы на каждой смене типа ордера.
 *
 * Второй отказ и делает повторный клик по тому же уровню рабочим: `pickLevel`
 * зовёт `setOrderType(LIMIT)` перед `setLimitPrice`, поэтому цена успевает
 * смениться дважды — `69990n → undefined → 69990n`, — и первое сравнение уже
 * не тождественно.
 *
 * Возвращает предикат типа, а не просто `boolean`: вызывающий после проверки
 * печатает `next` через `Price.fmt`, и сужение здесь избавляет его от
 * повторной проверки на «нет значения» — а заодно от соблазна привести тип
 * кастом.
 *
 * @param prev - Значение до записи в стор.
 * @param next - Значение после записи.
 */
export function shouldAdoptLevel(
  prev: bigint | null | undefined,
  next: bigint | null | undefined,
): next is bigint {
  if (next === prev) return false;
  return next !== null && next !== undefined;
}
