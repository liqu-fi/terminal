import { describe, expect, it } from "vitest";

import { BOOK_ROW_PX, slotsForHeight } from "../useBookSlots";

/** Высота хрома сетки: шапка колонок + строка спреда + полоса дисбаланса. */
const CHROME = 22 + 28 + 20;

describe("slotsForHeight", () => {
  it("делит свободную высоту на строки — по стороне в двустороннем режиме", () => {
    // Ровно десять строк на сторону: хром + 20 строк.
    expect(slotsForHeight(CHROME + 20 * BOOK_ROW_PX, 2)).toBe(10);
  });

  it("отдаёт одной стороне место, которое делили две", () => {
    expect(slotsForHeight(CHROME + 20 * BOOK_ROW_PX, 1)).toBe(20);
  });

  it("не выдаёт строк больше, чем помещается", () => {
    // Панель на пиксель ниже одиннадцатой пары строк — одиннадцатую рисовать
    // некуда, и книга обязана обрезаться сама, а не вылезти за карточку.
    expect(slotsForHeight(CHROME + 22 * BOOK_ROW_PX - 1, 2)).toBe(10);
  });

  it("держит минимум на панели, в которую не помещается ничего", () => {
    // Нулевая высота — это первый кадр, до измерения: минимум лучше пустой
    // сетки, которая мигала бы при каждой смене вкладки.
    expect(slotsForHeight(0, 2)).toBe(4);
    expect(slotsForHeight(CHROME, 2)).toBe(4);
  });

  it("не разгоняет глубину запроса на большом мониторе", () => {
    expect(slotsForHeight(5_000, 1)).toBe(25);
  });
});
